using System.Net;
using System.Security.Cryptography;
using System.Security.Cryptography.X509Certificates;

namespace NLightning.Testing.Lnd.Tests.TestUtils;

/// <summary>Self-signed ECDSA P-256 certificates like LND's tls.cert (its own root, localhost and 127.0.0.1 in the SAN).</summary>
internal static class TestCertificates
{
    /// <summary>A certificate with its private key, usable as a TLS server certificate.</summary>
    public static X509Certificate2 CreateServerCertificate(string commonName = "lnd autogenerated cert")
    {
        using var key = ECDsa.Create(ECCurve.NamedCurves.nistP256);
        var request = new CertificateRequest($"O=lnd, CN={commonName}", key, HashAlgorithmName.SHA256);
        var san = new SubjectAlternativeNameBuilder();
        san.AddDnsName("localhost");
        san.AddIpAddress(IPAddress.Loopback);
        request.CertificateExtensions.Add(san.Build());
        request.CertificateExtensions.Add(new X509BasicConstraintsExtension(true, false, 0, true));
        request.CertificateExtensions.Add(
            new X509EnhancedKeyUsageExtension([new Oid("1.3.6.1.5.5.7.3.1")], false));

        using var ephemeral = request.CreateSelfSigned(DateTimeOffset.UtcNow.AddDays(-1),
                                                       DateTimeOffset.UtcNow.AddDays(30));
        // Round trip through PKCS#12 so the key is usable by every platform's TLS stack (macOS refuses ephemeral keys).
        return X509CertificateLoader.LoadPkcs12(ephemeral.Export(X509ContentType.Pkcs12), null,
                                                X509KeyStorageFlags.Exportable);
    }

    /// <summary>The certificate as LND writes tls.cert (PEM, public part only).</summary>
    public static byte[] ToPem(X509Certificate2 certificate) =>
        System.Text.Encoding.ASCII.GetBytes(certificate.ExportCertificatePem() + "\n");

    /// <summary>The certificate as DER (public part only).</summary>
    public static byte[] ToDer(X509Certificate2 certificate) => certificate.RawData;
}