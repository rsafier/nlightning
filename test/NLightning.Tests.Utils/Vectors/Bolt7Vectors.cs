/// <summary>
/// One BOLT 7 message captured from a real implementation.
/// </summary>
/// <param name="Type">The message type (256 channel_announcement, 257 node_announcement, 258 channel_update,
/// 259 announcement_signatures).</param>
/// <param name="Source">The implementation and version that sent it.</param>
/// <param name="PayloadHex">The payload exactly as received (without the u16 type prefix).</param>
[ExcludeFromCodeCoverage]
public sealed record Bolt7CapturedMessage(ushort Type, string Source, string PayloadHex)
{
    /// <summary>
    /// The payload bytes.
    /// </summary>
    public byte[] Payload => Convert.FromHexString(PayloadHex);

    /// <summary>
    /// The whole wire message: the big-endian u16 type, then the payload.
    /// </summary>
    public byte[] Wire => [(byte)(Type >> 8), (byte)Type, .. Payload];

    public override string ToString() => $"{Source} {Type} ({PayloadHex.Length / 2} bytes, {PayloadHex[..16]}...)";
}

